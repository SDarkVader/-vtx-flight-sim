import assert from 'node:assert/strict';
import {thrustFraction,wheelAngle} from '../public/vtx-env/phantom-effects.js';
import {rotorVisualOffset} from '../public/rotor-visual.js';
assert.equal(thrustFraction(0,100),0);
assert.equal(thrustFraction(50,100),.5);
assert.equal(thrustFraction(200,100),1);
assert.equal(thrustFraction(-1,100),0);
assert.equal(thrustFraction(undefined,100),0);
assert.equal(thrustFraction(5,0),0);
assert.equal(wheelAngle(undefined,1),null);
assert.equal(wheelAngle(2,undefined),2);
assert.equal(wheelAngle(2,-.5),1.5);
assert.equal(rotorVisualOffset(10,100,1,true,false),1);
assert.equal(rotorVisualOffset(-10,100,1,true,false),-1);
assert.equal(rotorVisualOffset(10,100,.5,true,false),.5);
assert.equal(rotorVisualOffset(10,100,1,true,true),0);
assert.equal(rotorVisualOffset(10,100,1,false,false),0);
assert.equal(rotorVisualOffset(10,500,1,true,false),1.2);
console.log('Phantom thrust and wheel presentation checks passed');
